#!/usr/bin/env python3
"""BOOKmine library tool — add, update, and remove books offline.

The source of truth is library.json; every command that changes it also
regenerates data.js, which is what the website reads. Covers come from
Open Library, which needs no API key at all.

Usage:
  ./bookmine.py add "Dune" --score 9.5
  ./bookmine.py add "The Name of the Wind" --status reading
  ./bookmine.py start dune                 # -> reading, stamps today
  ./bookmine.py finish dune --score 9.5    # -> read, stamps today
  ./bookmine.py update dune --score 10 --notes "the spice must flow"
  ./bookmine.py remove dune
  ./bookmine.py list
  ./bookmine.py regen        # rebuild data.js from library.json
  ./bookmine.py check        # scan the library for duplicate entries

No dependencies beyond the standard library.
"""

import argparse
import datetime
import json
import re
import sys
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LIBRARY_PATH = ROOT / "library.json"
DATA_JS_PATH = ROOT / "data.js"
COVERS_DIR = ROOT / "covers"

OL_API = "https://openlibrary.org"
OL_COVERS = "https://covers.openlibrary.org"
UA = {"User-Agent": "bookmine/1.0 (personal reading log)"}

SEARCH_FIELDS = ",".join([
    "key", "title", "author_name", "author_key", "first_publish_year",
    "cover_i", "number_of_pages_median", "ratings_average", "ratings_count",
    "edition_count", "subject", "language",
])

STATUSES = ("reading", "toread", "read")

DATA_JS_HEADER = """\
// GENERATED by bookmine.py from library.json — do not edit by hand.
// Edit entries with:  ./bookmine.py add|update|remove   (see ./bookmine.py --help)

const LIBRARY = """


# ---------- library file handling ----------

def load_library():
    if not LIBRARY_PATH.exists():
        return []
    return json.loads(LIBRARY_PATH.read_text(encoding="utf-8"))


def save_library(lib):
    LIBRARY_PATH.write_text(json.dumps(lib, indent=2, ensure_ascii=False) + "\n",
                            encoding="utf-8")
    DATA_JS_PATH.write_text(DATA_JS_HEADER + json.dumps(lib, indent=2, ensure_ascii=False) + ";\n",
                            encoding="utf-8")
    print(f"saved {len(lib)} entries -> library.json + data.js")
    dupes = library_duplicates(lib)
    if dupes:
        names = "; ".join(" / ".join(f"[{e['id']}]" for e in g) for g in dupes)
        print(f"warning: possible duplicates: {names}  (run ./bookmine.py check)")


def slugify(text):
    """Accents fold to ASCII ('Gödel' -> 'godel'); scripts that don't fold at
    all (Cyrillic, CJK) come back empty so the caller can pick a fallback."""
    folded = unicodedata.normalize("NFKD", text or "")
    folded = "".join(c for c in folded if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "-", folded.lower()).strip("-")


def unique_slug(lib, title, *fallbacks):
    base = slugify(title)[:60]
    for alt in fallbacks:                 # e.g. the author, then the OL work id
        if base:
            break
        base = slugify(alt)[:60]
    base = base or "book"
    slug, n = base, 2
    ids = {e["id"] for e in lib}
    while slug in ids:
        slug = f"{base}-{n}"
        n += 1
    return slug


def find_entry(lib, key):
    """Find by exact id, then by title or author substring."""
    for e in lib:
        if e["id"] == key:
            return e
    # fold accents both ways, so 'hrabe' still finds 'Hrabě'
    k = slugify(key)
    matches = [e for e in lib
               if k and (k in slugify(e["title"]) or k in slugify(e.get("author") or ""))]
    if len(matches) == 1:
        return matches[0]
    if len(matches) > 1:
        sys.exit("ambiguous match: " + ", ".join(e["id"] for e in matches))
    sys.exit(f"no entry matching '{key}' (try ./bookmine.py list)")


# ---------- Open Library ----------

def ol_get(path, **params):
    url = f"{OL_API}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=25) as resp:
        return json.load(resp)


def search_books(query, author=None, limit=10):
    """Return candidate dicts from Open Library's work search."""
    params = {"q": query, "limit": limit, "fields": SEARCH_FIELDS}
    if author:
        params["author"] = author
    data = ol_get("/search.json", **params)
    out = []
    for r in data.get("docs", []):
        if not r.get("title"):
            continue
        out.append({
            "key": r.get("key"),                       # /works/OL893414W
            "title": r["title"],
            "authors": r.get("author_name") or [],
            "author_keys": r.get("author_key") or [],
            "year": r.get("first_publish_year"),
            "cover_id": r.get("cover_i"),
            "pages": r.get("number_of_pages_median"),
            "ol_rating": r.get("ratings_average"),
            "ol_rating_count": r.get("ratings_count") or 0,
            "editions": r.get("edition_count") or 0,
            "subjects": r.get("subject") or [],
        })
    return out


def pick_result(results, first=False, pick=None):
    if not results:
        sys.exit("no Open Library results found. Try a more specific query, "
                 "or add --author.")
    if pick is not None:
        if not 1 <= pick <= len(results):
            sys.exit(f"--pick {pick} is out of range (got {len(results)} results)")
        return results[pick - 1]
    if first or len(results) == 1:
        return results[0]
    print("\nmatches:")
    for i, r in enumerate(results[:8], 1):
        who = ", ".join(r["authors"][:2]) or "unknown author"
        year = r["year"] or "????"
        pages = f"{r['pages']}p" if r["pages"] else "  — "
        rating = f"★{r['ol_rating']:.1f}" if r["ol_rating"] else "    "
        print(f"  {i}. {r['title'][:44]:46} {who[:24]:26} {year}  "
              f"{pages:>6}  {rating}  {r['editions']} eds")
    while True:
        choice = input("pick a number (or q to abort): ").strip()
        if choice.lower() == "q":
            sys.exit("aborted.")
        if choice.isdigit() and 1 <= int(choice) <= min(len(results), 8):
            return results[int(choice) - 1]


def clean_description(desc):
    """OL descriptions are markdown-ish and often carry a source footer."""
    if isinstance(desc, dict):
        desc = desc.get("value", "")
    if not desc:
        return ""
    desc = re.split(r"\n\s*-{4,}", desc)[0]
    desc = re.sub(r"\(\[source\]\[\d+\]\)", "", desc)
    desc = re.sub(r"\[(\d+)\]:\s*\S+", "", desc)
    desc = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", desc)   # markdown links
    desc = re.sub(r"\s*\n\s*\n\s*", " ", desc)
    return re.sub(r"\s+", " ", desc).strip()


def fetch_work(work_key):
    """Pull the work record for its description and curated subjects."""
    try:
        return ol_get(f"{work_key}.json")
    except (urllib.error.URLError, urllib.error.HTTPError, ValueError):
        return {}


# ---------- genres ----------

# Open Library's `subject` field is a firehose of noise — real values include
# "nyt:mass-market-monthly=2021-11-07" and "Roman ame ricain". These rules fold
# that mess into a short, chip-sized vocabulary. First rule that matches wins,
# and a book keeps only its first few, so the order is the priority: form of the
# book, then the fiction genres, then non-fiction subjects. Fiction has to come
# first or a novel burns its three slots on topics it merely mentions.
GENRE_RULES = [
    # --- form ---
    ("Comics",      ["manga", "comic", "graphic novel", "bandes dessin"]),
    ("Poetry",      ["poetry", "poems", "verse"]),
    ("Plays",       ["drama", "plays", "theater", "theatre"]),
    # --- fiction genres ---
    ("Sci-Fi",      ["science fiction", "science-fiction", "dystopia", "space opera",
                     "cyberpunk", "time travel", "space flight", "extraterrestrial"]),
    ("Fantasy",     ["fantasy", "magic", "wizard", "dragon", "sorcery", "mythical",
                     "imaginary places", "elves", "witches"]),
    ("Horror",      ["horror", "ghost", "vampire", "supernatural", "monsters", "occult"]),
    ("Crime",       ["detective", "crime", "murder", "noir", "mystery", "police"]),
    ("Thriller",    ["thriller", "suspense", "espionage", "spy"]),
    ("Romance",     ["romance", "love stories", "courtship"]),
    ("Western",     ["western", "cowboys", "frontier"]),
    ("Adventure",   ["adventure", "survival", "sea stories", "quests"]),
    # --- non-fiction subjects ---
    ("Memoir",      ["memoir", "autobiograph", "personal narrative"]),
    ("Biography",   ["biography", "biographies", "biographical"]),
    ("True Crime",  ["true crime"]),
    ("Philosophy",  ["philosophy", "philosophers", "ethics", "stoic", "metaphysic"]),
    ("Psychology",  ["psycholog", "cognition", "consciousness", "mental health"]),
    ("Religion",    ["religion", "christian", "bible", "theolog", "buddhis", "islam", "spiritual"]),
    ("Politics",    ["politic", "government", "democracy"]),
    ("Economics",   ["economic", "finance", "capitalism", "money"]),
    ("Business",    ["business", "management", "entrepreneur", "leadership", "marketing"]),
    ("Self-Help",   ["self-help", "self help", "personal development", "productivity", "habits"]),
    ("Technology",  ["computer", "programming", "software", "engineering", "internet",
                     "artificial intelligence"]),
    # bare "science" is deliberately absent — it matches "science fiction"
    ("Science",     ["physics", "biology", "mathematic", "astronomy", "chemistry",
                     "evolution", "neuroscience", "cosmolog", "scientists"]),
    ("Nature",      ["ecology", "environmental", "natural history", "animals", "botany"]),
    ("Travel",      ["travel", "voyages and travels", "description and travel"]),
    ("Art",         ["painting", "photography", "architecture", "art history"]),
    ("Essays",      ["essays", "essai"]),
    ("War",         ["war", "military", "soldiers"]),
    ("History",     ["history", "historical", "civilization", "ancient", "medieval"]),
    # --- audience / catch-alls ---
    ("Young Adult", ["young adult", "teenage", "juvenile fiction", "coming of age"]),
    ("Children",    ["children", "picture book", "juvenile literature"]),
    ("Short Stories", ["short stories"]),
    ("Classics",    ["classic", "classical literature"]),
]


def derive_genres(subjects, limit=2):
    """Fold Open Library's noisy subject list into a few clean chips."""
    blob = [s.lower() for s in subjects if isinstance(s, str)]
    # drop OL's machine-generated tags outright
    blob = [s for s in blob if not re.match(r"^(nyt:|award:|accessible book|in library|protected daisy)", s)]
    hits = []
    for genre, needles in GENRE_RULES:
        if any(any(n in s for n in needles) for s in blob):
            hits.append(genre)
        if len(hits) >= limit:
            break
    if not hits:
        if any("fiction" in s for s in blob):
            hits = ["Fiction"]
        elif blob:
            hits = ["Nonfiction"]
        else:
            hits = ["Unsorted"]
    return hits


# ---------- covers ----------

def download(url, dest):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=45) as resp:
        data = resp.read()
    if len(data) < 1000:          # OL serves a 1x1 gif when it has no image
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return True


def download_cover(cover_id, slug):
    if not cover_id:
        print("no cover on Open Library — the site will print a cloth one instead.")
        return None
    dest = COVERS_DIR / f"{slug}.jpg"
    try:
        if download(f"{OL_COVERS}/b/id/{cover_id}-L.jpg", dest):
            print(f"cover -> covers/{slug}.jpg")
            return f"covers/{slug}.jpg"
    except (urllib.error.URLError, urllib.error.HTTPError) as err:
        print(f"cover download failed ({err}) — using a printed cloth cover.")
    return None


def download_author_photo(author_key):
    """Author portraits are shared between books, so fetch each one once."""
    if not author_key:
        return None
    rel = f"covers/authors/{author_key}.jpg"
    dest = ROOT / rel
    if dest.exists():
        return rel
    try:
        if download(f"{OL_COVERS}/a/olid/{author_key}-M.jpg", dest):
            print(f"author photo -> {rel}")
            return rel
    except (urllib.error.URLError, urllib.error.HTTPError):
        pass
    return None


# ---------- field parsing ----------

def today():
    return datetime.date.today().isoformat()


def check_date(text, label):
    if text is None:
        return None
    try:
        datetime.date.fromisoformat(text)
    except ValueError:
        sys.exit(f"bad --{label}, expected YYYY-MM-DD (got '{text}')")
    return text


def split_genres(text):
    return [g.strip() for g in text.split(",") if g.strip()]


# ---------- duplicate detection ----------

def normalize_title(title):
    """Fold case/punctuation so 'Dune!' == 'dune'."""
    return re.sub(r"[^a-z0-9]+", " ", title.lower()).strip()


def find_duplicates(lib, work_key, title, author):
    """Entries that look like the same book: same OL work, or same
    normalized title + first author (catches hand-added entries)."""
    norm = normalize_title(title)
    who = normalize_title(author or "")
    dupes = []
    for e in lib:
        if work_key and e.get("olKey") == work_key:
            dupes.append((e, "same Open Library work"))
        elif normalize_title(e["title"]) == norm and normalize_title(e.get("author") or "") == who:
            dupes.append((e, "same title + author"))
    return dupes


def confirm_duplicate(dupes, interactive):
    print("\nalready on the shelves:")
    for e, why in dupes:
        print(f"  [{e['id']}] {e['title']} — {e.get('author', '?')} "
              f"({e.get('year', '?')}) — {e['status']}  ({why})")
    print("to change an existing entry:  ./bookmine.py update <id> ...")
    if not interactive:
        print("refusing to add a duplicate (pass --again to override).")
        return False
    return input("add it anyway? [y/N]: ").strip().lower() in ("y", "yes")


def library_duplicates(lib):
    by_work, by_title = {}, {}
    for e in lib:
        if e.get("olKey"):
            by_work.setdefault(e["olKey"], []).append(e)
        by_title.setdefault((normalize_title(e["title"]),
                             normalize_title(e.get("author") or "")), []).append(e)
    groups, reported = [], set()
    for g in list(by_work.values()) + list(by_title.values()):
        ids = frozenset(e["id"] for e in g)
        if len(g) > 1 and ids not in reported:
            reported.add(ids)
            groups.append(g)
    return groups


# ---------- status transitions ----------

def set_status(entry, status, started=None, finished=None):
    """Move an entry between shelves, stamping the dates that implies.
    Dates given explicitly always win over the ones a move would stamp."""
    if status == "toread":
        entry.pop("started", None)
        entry.pop("finished", None)
        entry["status"] = status
        return
    if started:
        entry["started"] = started
    if finished:
        entry["finished"] = finished
    if status == "reading":
        entry.setdefault("started", today())
        entry.pop("finished", None)
    elif status == "read":
        entry.setdefault("finished", today())
        # a book read before you started tracking gets a same-day span
        entry.setdefault("started", entry["finished"])
    entry["status"] = status


# ---------- commands ----------

def cmd_add(args):
    lib = load_library()
    if args.status is None:
        # a score means you've finished it; otherwise it's a plan
        args.status = "read" if args.score is not None else "toread"
    started = check_date(args.started, "started")
    finished = check_date(args.finished, "finished")

    results = search_books(args.title, author=args.author)
    chosen = pick_result(results, first=args.first, pick=args.pick)
    if args.title_as:
        # Open Library indexes many works under their original-language title
        # ("Мастер и Маргарита"); --title-as puts your name on the spine.
        chosen["title"] = args.title_as
    first_author = args.author_as or (chosen["authors"][0] if chosen["authors"] else None)

    dupes = find_duplicates(lib, chosen["key"], chosen["title"], first_author)
    if dupes and not args.again:
        if args.score is not None:
            # re-adding something with a score = re-score the existing entry
            e = dupes[0][0]
            e["score"] = args.score
            set_status(e, args.status, started, finished)
            if args.notes:
                e["notes"] = args.notes
            save_library(lib)
            print(f"'{e['title']}' was already on the shelves — updated it instead: "
                  f"score {e['score']}, {e['status']} [{e['id']}]")
            return
        if not confirm_duplicate(dupes, interactive=not args.first):
            sys.exit(1)

    work = fetch_work(chosen["key"]) if chosen["key"] else {}
    subjects = list(chosen["subjects"]) + list(work.get("subjects") or [])
    slug = unique_slug(lib, chosen["title"], first_author or "",
                       (chosen["key"] or "").rsplit("/", 1)[-1])
    cover = download_cover(chosen["cover_id"], slug)
    author_photo = download_author_photo(
        chosen["author_keys"][0] if chosen["author_keys"] else None)

    entry = {
        "id": slug,
        "title": chosen["title"],
        "author": first_author or "Unknown",
        "authors": chosen["authors"],
        "status": args.status,
        "year": args.year or chosen["year"],
        "pages": args.pages or chosen["pages"],
        "genres": split_genres(args.genres) if args.genres else derive_genres(subjects),
        "score": args.score,
        "synopsis": clean_description(work.get("description")),
        "added": today(),
        "cover": cover,
        "authorPhoto": author_photo,
        "olKey": chosen["key"],
        "olCoverId": chosen["cover_id"],
        "olRating": round(chosen["ol_rating"], 2) if chosen["ol_rating"] else None,
        "olRatingCount": chosen["ol_rating_count"],
    }
    if args.notes:
        entry["notes"] = args.notes
    # set_status expects an existing status to compare against
    entry["status"] = "toread"
    set_status(entry, args.status, started, finished)

    lib.append(entry)
    save_library(lib)
    print(f"added: {entry['title']} — {entry['author']} ({entry['year']}) "
          f"[{entry['id']}] as {entry['status']}")


def cmd_update(args):
    lib = load_library()
    e = find_entry(lib, args.id)
    if args.score is not None:
        e["score"] = args.score
        # scoring something means you've read it (unless told otherwise)
        if not args.status and e["status"] != "read":
            args.status = "read"
    if args.status:
        set_status(e, args.status,
                   check_date(args.started, "started"),
                   check_date(args.finished, "finished"))
    if args.started:
        e["started"] = check_date(args.started, "started")
    if args.finished:
        e["finished"] = check_date(args.finished, "finished")
    if args.title_as:
        e["title"] = args.title_as
    if args.author_as:
        e["author"] = args.author_as
    if args.pages:
        e["pages"] = args.pages
    if args.year:
        e["year"] = args.year
    if args.genres:
        e["genres"] = split_genres(args.genres)
    if args.notes is not None:
        if args.notes:
            e["notes"] = args.notes
        else:
            e.pop("notes", None)
    save_library(lib)
    print(f"updated: {e['title']} [{e['id']}] — {e['status']}")


def cmd_start(args):
    lib = load_library()
    e = find_entry(lib, args.id)
    set_status(e, "reading", check_date(args.date, "date"))
    save_library(lib)
    print(f"reading: {e['title']} — started {e['started']}")


def cmd_finish(args):
    lib = load_library()
    e = find_entry(lib, args.id)
    if args.score is not None:
        e["score"] = args.score
    set_status(e, "read", finished=check_date(args.date, "date"))
    days = reading_days(e)
    tail = f" in {days} day{'s' if days != 1 else ''}" if days else ""
    save_library(lib)
    print(f"finished: {e['title']}{tail}"
          + (f" — scored {e['score']}" if e.get("score") is not None else ""))


def cmd_remove(args):
    lib = load_library()
    e = find_entry(lib, args.id)
    lib.remove(e)
    cover = e.get("cover")
    if cover and (ROOT / cover).exists() and not args.keep_cover:
        (ROOT / cover).unlink()
        print(f"deleted {cover}")
    save_library(lib)
    print(f"removed: {e['title']} [{e['id']}]")


def reading_days(e):
    if not (e.get("started") and e.get("finished")):
        return None
    try:
        d = (datetime.date.fromisoformat(e["finished"])
             - datetime.date.fromisoformat(e["started"])).days
    except ValueError:
        return None
    return max(d, 1)


def cmd_list(args):
    lib = load_library()
    order = {"reading": 0, "toread": 1, "read": 2}
    for e in sorted(lib, key=lambda x: (order.get(x["status"], 9), x["title"])):
        score = f"{e['score']:>4}" if e.get("score") is not None else "  — "
        pages = f"{e['pages']:>4}p" if e.get("pages") else "     "
        when = e.get("finished") or e.get("started") or ""
        print(f"{e['status']:8} {score} {pages}  {e['title'][:42]:44} "
              f"{(e.get('author') or '')[:22]:24} {when}  [{e['id']}]")
    print(f"\n{len(lib)} books")


def cmd_stats(args):
    lib = load_library()
    read = [e for e in lib if e["status"] == "read"]
    rated = [e for e in read if e.get("score") is not None]
    pages = sum(e["pages"] for e in read if e.get("pages"))
    print(f"{len(lib)} books — {sum(1 for e in lib if e['status']=='reading')} reading, "
          f"{sum(1 for e in lib if e['status']=='toread')} to read, {len(read)} read")
    if pages:
        print(f"{pages:,} pages read")
    if rated:
        print(f"average score {sum(e['score'] for e in rated)/len(rated):.2f} "
              f"over {len(rated)} rated")
    by_year = {}
    for e in read:
        if e.get("finished"):
            by_year.setdefault(e["finished"][:4], []).append(e)
    for year in sorted(by_year, reverse=True):
        got = by_year[year]
        p = sum(e["pages"] for e in got if e.get("pages"))
        print(f"  {year}: {len(got):>3} books" + (f", {p:,} pages" if p else ""))


def cmd_regen(args):
    save_library(load_library())


def cmd_check(args):
    lib = load_library()
    groups = library_duplicates(lib)
    if not groups:
        print(f"no duplicates found in {len(lib)} books.")
        return
    print(f"{len(groups)} possible duplicate group(s):\n")
    for g in groups:
        for e in g:
            print(f"  [{e['id']}] {e['title']} — {e.get('author','?')} "
                  f"({e.get('year','?')}) — {e['status']}, olKey={e.get('olKey')}")
        print("  keep one, remove the rest:  ./bookmine.py remove <id>\n")
    sys.exit(1)


def cmd_reset(args):
    lib = load_library()
    if not args.yes:
        sys.exit(f"this would delete all {len(lib)} books and their covers. "
                 "Re-run with --yes if you mean it.")
    for e in lib:
        cover = e.get("cover")
        if cover and (ROOT / cover).exists():
            (ROOT / cover).unlink()
    save_library([])
    print(f"cleared {len(lib)} books.")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    a = sub.add_parser("add", help="look a book up on Open Library and add it")
